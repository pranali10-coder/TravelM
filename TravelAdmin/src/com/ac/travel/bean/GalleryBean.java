package com.ac.travel.bean;

public class GalleryBean 
{
	private int gallery_id;
	private String gallery_name;
	private String gallery_img;
	private String gallery_description;
	private String gallery_status;
	
	public int getGallery_id() {
		return gallery_id;
	}
	public void setGallery_id(int gallery_id) {
		this.gallery_id = gallery_id;
	}
	public String getGallery_name() {
		return gallery_name;
	}
	public void setGallery_name(String gallery_name) {
		this.gallery_name = gallery_name;
	}
	public String getGallery_img() {
		return gallery_img;
	}
	public void setGallery_img(String gallery_img) {
		this.gallery_img = gallery_img;
	}
	public String getGallery_description() {
		return gallery_description;
	}
	public void setGallery_description(String gallery_description) {
		this.gallery_description = gallery_description;
	}
	public String getGallery_status() {
		return gallery_status;
	}
	public void setGallery_status(String gallery_status) {
		this.gallery_status = gallery_status;
	}
	
}
